/**
 * Generates `css/theme.css` (Tailwind v4 `@theme`) from `src/tokens.ts`.
 *
 * Run: pnpm --filter @cute-teachy/tokens generate
 * Requires Node >= 23.6 (native TypeScript type-stripping).
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  breakpoints,
  colors,
  layout,
  radius,
  shadows,
  tones,
  typography,
} from '../src/tokens.ts';

const kebab = (value: string): string =>
  value.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/\./g, '_').toLowerCase();

const hexToRgb = (hex: string): string => {
  const n = Number.parseInt(hex.slice(1), 16);
  return `${(n >> 16) & 255} ${(n >> 8) & 255} ${n & 255}`;
};

const lines: string[] = [];
const push = (line = ''): void => {
  lines.push(line);
};

push('/* AUTO-GENERATED by packages/tokens/scripts/generate-css.ts – do not edit by hand. */');
push();
push('@theme {');
push('  /* Reset Tailwind defaults so only design-system values are available */');
push('  --color-*: initial;');
push('  --radius-*: initial;');
push('  --shadow-*: initial;');
push();
push('  --color-white: #ffffff;');
push('  --color-transparent: transparent;');
push('  --color-current: currentColor;');
for (const [name, value] of Object.entries(colors)) {
  push(`  --color-${kebab(name)}: ${value};`);
}
push();
push('  /* Tag / category tones */');
for (const [name, tone] of Object.entries(tones)) {
  push(`  --color-tone-${name}: ${tone.bg};`);
  push(`  --color-tone-${name}-fg: ${tone.fg};`);
  push(`  --color-tone-${name}-accent: ${tone.accent};`);
}
push();
push('  --font-sans: var(--font-quicksand), "Quicksand", ui-rounded, system-ui, sans-serif;');
push();
for (const [name, t] of Object.entries(typography)) {
  const key = kebab(name);
  push(`  --text-${key}: ${t.fontSize}px;`);
  push(`  --text-${key}--line-height: ${t.lineHeight}px;`);
  push(`  --text-${key}--font-weight: ${t.fontWeight};`);
  push(`  --text-${key}--letter-spacing: ${t.letterSpacing}px;`);
}
push();
push(`  --spacing: ${layout.baseUnit}px;`);
push(`  --spacing-container: ${layout.containerPadding}px;`);
push(`  --spacing-gutter: ${layout.gutter}px;`);
push(`  --spacing-touch: ${layout.minTouchTarget}px;`);
push(`  --spacing-sidebar: ${layout.sidebarWidth}px;`);
push(`  --spacing-topbar: ${layout.topbarHeight}px;`);
push(`  --container-content: ${layout.contentMaxWidth}px;`);
push();
for (const [name, value] of Object.entries(radius)) {
  if (name === 'none') continue;
  push(`  --radius-${name}: ${value}px;`);
}
push();
const shadowRgb = hexToRgb(colors.shadow);
for (const [name, s] of Object.entries(shadows)) {
  push(`  --shadow-${name}: 0 ${s.offsetY}px ${s.blur}px rgb(${shadowRgb} / ${s.opacity});`);
}
push();
for (const [name, value] of Object.entries(breakpoints)) {
  push(`  --breakpoint-${name}: ${value}px;`);
}
push('}');
push();

const here = dirname(fileURLToPath(import.meta.url));
const outFile = resolve(here, '../css/theme.css');
mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, lines.join('\n'), 'utf8');
console.log(`✓ Wrote ${outFile}`);
